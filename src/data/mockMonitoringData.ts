// Generate 30 days of realistic trend data
export const generateTrendData = (): TrendDataPoint[] => {
  const list: TrendDataPoint[] = [];
  const baseDate = new Date('2026-09-23');

  for (let i = 29; i >= 0; i--) {
    const d = new Date(baseDate);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().slice(0, 10);
    const dateLabel = `${d.getMonth() + 1}/${d.getDate()}`;

    // Base fluctuations
    const waveSin = Math.sin(i * 0.4);
    const randOffset = (Math.random() - 0.5) * 2;

    // Timeliness around 93%~97%
    const timelinessRate = +(94.5 + waveSin * 2.2 + randOffset).toFixed(1);

    // Stockout method 1: 拣货点缺货上报 / 拣货总次数 (around 1.2% ~ 3.5%)
    const totalPickingOps = Math.floor(4800 + Math.sin(i * 0.3) * 600 + Math.random() * 300);
    const pickingReports = Math.floor(totalPickingOps * (0.015 + (waveSin > 0 ? 0.008 : 0.003) + Math.random() * 0.006));
    const stockoutRatePicking = +((pickingReports / totalPickingOps) * 100).toFixed(2);

    // Stockout method 2: 缺货SKU数 / 波次SKU总数 (around 2.5% ~ 6.0%)
    const totalWaveSkus = Math.floor(620 + Math.random() * 80);
    const stockoutSkus = Math.floor(totalWaveSkus * (0.032 + (waveSin > 0 ? 0.015 : 0.005) + Math.random() * 0.01));
    const stockoutRateSku = +((stockoutSkus / totalWaveSkus) * 100).toFixed(2);

    // Total pieces and tasks
    const totalPieces = Math.floor(28000 + Math.sin(i * 0.5) * 4500 + Math.random() * 2000);
    const totalTasks = Math.floor(totalPieces / 140);
    const stuckCount = Math.max(1, Math.floor(8 - (timelinessRate - 90) * 0.8 + Math.random() * 2));

    list.push({
      date: dateStr,
      dateLabel,
      timelinessRate,
      targetRate: 95.0,
      pickingReports,
      totalPickingOps,
      stockoutRatePicking,
      stockoutSkus,
      totalWaveSkus,
      stockoutRateSku,
      totalPieces,
      totalTasks,
      stuckCount,
    });
  }

  return list;
};

